/*  Конфигурация модуля (define-ы, меняются до включения заголовка)         */
/* ------------------------------------------------------------------------ */

/** Ёмкость общего статического буфера записей (без malloc). Верхний предел -
 *  256, жёстко ограничен библиотекой: пороги приоритетов задаются как
 *  uint8_t (0..255), чтобы пользователь конфигурацией не мог случайно выйти
 *  за границы буфера. Можно уменьшить (например, для МК с малым ОЗУ - каждая
 *  запись теперь занимает 16 байт, а не 8) через #define LOGGER_BUFFER_CAPACITY
 *  перед включением этого заголовка, но не увеличить сверх 256. */
#ifndef LOGGER_BUFFER_CAPACITY
#define LOGGER_BUFFER_CAPACITY       256U
#endif
#if LOGGER_BUFFER_CAPACITY > 256U
#error "LOGGER_BUFFER_CAPACITY не может превышать 256 (пороги приоритетов - uint8_t)"
#endif

/** Уровень заполнения буфера (записей), при достижении которого сброс в
 *  write_fn запускается НЕЗАВИСИМО от порогов приоритетов. Нужен, чтобы
 *  write_fn (особенно медленный - стирание сектора flash) уже шёл, пока
 *  приём продолжается в свободной части кольца. По умолчанию - половина
 *  ёмкости. Равен LOGGER_BUFFER_CAPACITY - отключает такой запуск (останется
 *  только сброс по порогам и по полному буферу). */
#ifndef LOGGER_BUFFER_WATERMARK
#define LOGGER_BUFFER_WATERMARK      ((LOGGER_BUFFER_CAPACITY + 1U) / 2U)
#endif

/** Сколько мс LOGGER_Log() в потоке (не в ISR, прерывания разрешены) ждёт
 *  освобождения места, если кольцо полно, а write_fn занят сбросом из другого
 *  контекста. По истечении запись отбрасывается и считается
 *  (LOGGER_GetDroppedCount()). 0 - не ждать никогда. В ISR/при PRIMASK=1
 *  ожидания нет вовсе. */
#ifndef LOGGER_OVERFLOW_WAIT_MS
#define LOGGER_OVERFLOW_WAIT_MS      200U
#endif

/** Сколько различных mark_id (см. LOGGER_Mark()) библиотека одновременно
 *  отслеживает статистикой (кол-во вызовов, первый/последний SysTick) для
 *  LOGGER_GetMarkFrequency(). mark_id обязан быть строго меньше этого числа,
 *  чтобы статистика велась (иначе сам лог всё равно происходит, просто без
 *  статистики). Небольшое значение по умолчанию, т.к. каждая запись
 *  статистики занимает ОЗУ; переопределяется через #define перед включением
 *  этого заголовка. */
#ifndef LOGGER_MARK_MAX_IDS
#define LOGGER_MARK_MAX_IDS 32U
#endif

/** Атрибут компилятора, применяемый к статическому буферу логов (s_buffer,
 *  LOGGER_BUFFER_CAPACITY записей) - позволяет разместить его в отдельной
 *  секции памяти, например если библиотека, занимающаяся сохранением логов в
 *  энергонезависимую память, требует конкретную область ОЗУ (скажем, под
 *  DMA). Пусто по умолчанию - буфер размещается компилятором как обычно.
 *  Переопределяется через #define перед включением этого заголовка:
 *      #define LOGGER_BUFFER_SECTION_ATTR __attribute__((section(".buffer")))
 */
#ifndef LOGGER_BUFFER_SECTION_ATTR
#define LOGGER_BUFFER_SECTION_ATTR
#endif

/** Источники времени для статистики частоты LOGGER_Mark()/
 *  LOGGER_GetMarkFrequency() - см. LOGGER_MARK_TIME_SOURCE ниже (доступность
 *  DWT - см. README.md). НЕ влияют на systick, попадающий в сами записи
 *  логов/буфер - тот всегда HAL_GetTick() (мс). */
#define LOGGER_MARK_TIME_SYSTICK_MS 0 /**< HAL_GetTick(), мс - по умолчанию, доступно везде */
#define LOGGER_MARK_TIME_DWT_MS     1 /**< DWT->CYCCNT, результат в мс - только Cortex-M3/M4/M7 */
#define LOGGER_MARK_TIME_DWT_US     2 /**< DWT->CYCCNT, результат в мкс - только Cortex-M3/M4/M7 */

/** Выбор источника времени для статистики меток - переопределяется через
 *  #define перед включением этого заголовка, например:
 *      #define LOGGER_MARK_TIME_SOURCE LOGGER_MARK_TIME_DWT_US
 *  При выборе любого из режимов DWT, LOGGER_Init() сам включает счётчик
 *  тактов ядра (CoreDebug->DEMCR TRCENA + DWT->CTRL CYCCNTENA) - никаких
 *  дополнительных действий от пользователя не требуется. */
#ifndef LOGGER_MARK_TIME_SOURCE
#define LOGGER_MARK_TIME_SOURCE LOGGER_MARK_TIME_SYSTICK_MS
#endif

/* ------------------------------------------------------------------------ */
/*  Пользовательские функции вывода/сохранения/времени                      */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Функция сохранения накопленных логов в энергонезависимую память,
 *         предоставляется пользователем при инициализации. Вызывается, когда
 *         по текущему максимальному приоритету буфера достигнут настроенный
 *         порог. Должна быть быстрой и не блокирующей надолго (вызывается из
 *         того же контекста, что и LOGGER_Log()).
 * @param  context      значение write_context, переданное в LOGGER_Init()
 * @param  data         указатель на массив LOGGER_Record_t подряд (буфер
 *                       логгера) - только на время вызова, копировать данные
 *                       нужно самостоятельно, если требуется асинхронная запись
 * @param  length_bytes  длина data в байтах (кратна sizeof(LOGGER_Record_t))
 */
typedef void (*LOGGER_MemoryWriteFn_t)(void *context, const uint8_t *data, uint32_t length_bytes);

/**
 * @brief  Функция вывода одной записи лога в консоль, предоставляется
 *         пользователем при инициализации - заменяет вывод по умолчанию в
 *         SWO. Вызывается на каждый LOGGER_Log()/LOGGER_Mark(), должна быть
 *         быстрой.
 * @param  context      значение console_context, переданное в LOGGER_Init()
 * @param  code         код лога
 * @param  source_id    идентификатор источника события (из LOGGER_Log())
 * @param  priority     приоритет лога (из таблицы кодов)
 * @param  value        значение переменной, переданное в LOGGER_Log()
 * @param  systick      HAL_GetTick() на момент события, мс с момента старта
 * @param  rtc_time     показание RTC на момент события, либо 0
 * @param  description  текстовое описание из таблицы кодов (NULL, если код
 *                       не найден в таблице)
 */
typedef void (*LOGGER_ConsoleWriteFn_t)(void *context, uint16_t code, uint16_t source_id,
                                         LOGGER_Priority_t priority, int32_t value,
                                         uint32_t systick, uint32_t rtc_time,
                                         const char *description);

/**
 * @brief  Функция получения текущего времени RTC, предоставляется
 *         пользователем при инициализации, ТОЛЬКО если в проекте реально
 *         настроен и включён RTC (через CubeMX). Формат возвращаемого
 *         значения - Unix-время (секунды с 1970, без часового пояса): в
 *         запись оно переносится как есть, а в текстовой строке лога
 *         переводится библиотекой в "ГГГГ-ММ-ДД ЧЧ:ММ:СС" (0 - RTC не используется).
 *         Должна быть быстрой (без чтения/пересчёта дат в духе mktime на
 *         каждый вызов, если это критично для скорости - закешируйте).
 * @param  context  значение rtc_context, переданное в LOGGER_Init()
 * @retval текущее время в представлении пользователя
 */
typedef uint32_t (*LOGGER_RtcTimeFn_t)(void *context);

/* ------------------------------------------------------------------------ */
/*  Конфигурация инициализации                                              */
/* ------------------------------------------------------------------------ */

typedef struct
{
    /** Функция записи буфера логов в энергонезависимую память. NULL - логи
     *  не буферизируются и не сохраняются, только выводятся. */
    LOGGER_MemoryWriteFn_t write_fn;

    /** Указатель, который будет передан write_fn первым аргументом (например,
     *  хэндл/заголовок драйвера памяти пользователя). Может быть NULL. */
    void *write_context;

    /** Функция вывода лога в консоль. NULL - используется вывод по умолчанию
     *  через SWO (ITM). */
    LOGGER_ConsoleWriteFn_t console_fn;

    /** Указатель, который будет передан console_fn первым аргументом. Может
     *  быть NULL. */
    void *console_context;

    /** Функция чтения текущего времени RTC. NULL - RTC не настроен/не
     *  используется, поле rtc_time в каждой записи будет равно 0. */
    LOGGER_RtcTimeFn_t rtc_time_fn;

    /** Указатель, который будет передан rtc_time_fn первым аргументом. Может
     *  быть NULL. */
    void *rtc_context;

    /** Сколько записей НИЗКОГО приоритета должно накопиться в буфере (в
     *  качестве текущего максимального приоритета буфера), чтобы вызвать
     *  запись в память. 1..255. Учитывается, только если write_fn != NULL. */
    uint8_t threshold_low;

    /** Аналогично для СРЕДНЕГО приоритета. Рекомендуется <= threshold_low. */
    uint8_t threshold_medium;

    /** Аналогично для ВЫСОКОГО приоритета. Рекомендуется <= threshold_medium -
     *  логи высокого приоритета обычно должны попадать в память чаще. */
    uint8_t threshold_high;
} LOGGER_Config_t;

/* ------------------------------------------------------------------------ */
/*  Инициализация                                                           */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Инициализирует логгер: проверяет корректность таблицы кодов
 *         (logger_codes.h - отсортирована по возрастанию, без повторов, не
 *         пересекается со служебным диапазоном 0x0000-0x00FF, приоритеты и
 *         длины описаний корректны) и конфигурации, применяет колбэки и
 *         пороги буферизации. Вся валидация выполняется здесь, один раз,
 *         чтобы LOGGER_Log() не делал проверок в рантайме. По завершении
 *         логирует служебное событие LOGGER_INTERNAL_CODE_INIT (только вывод,
 *         не буферизуется).
 *
 *         Необязательна - без вызова LOGGER_Init() (или до него) LOGGER_Log()
 *         работает в минимальном режиме "только вывод в SWO".
 *
 *         Повторный вызов (реинициализация) сначала сбрасывает в память уже
 *         накопленный буфер (если ранее была включена буферизация и в нём
 *         есть записи), затем применяет новую конфигурацию.
 *
 *         При отказе причина выводится служебным логом
 *         LOGGER_INTERNAL_CODE_INIT_FAIL (только вывод, через console_fn из
 *         переданного config, либо SWO): source_id = код проблемной записи
 *         таблицы (0, если причина не в записи), value = LOGGER_INIT_FAIL_*.
 *
 * @param  config  заполненная конфигурация
 * @retval HAL_OK; HAL_ERROR - config == NULL, таблица кодов пуста/не
 *         отсортирована/содержит повтор кода/код из служебного диапазона/
 *         некорректный приоритет/слишком длинное описание, либо (при
 *         заданном write_fn) один из порогов равен 0 или превышает
 *         LOGGER_BUFFER_CAPACITY
 */
HAL_StatusTypeDef LOGGER_Init(const LOGGER_Config_t *config);

/**
 * @brief  Формирует текстовую строку лога в буфер - в том же формате, что
 *         вывод по умолчанию в SWO, без printf/snprintf:
 *         "<RTC,19> <мс,8> <ГРУППА,8> <L|M|H> 0x<код> <src,4> <val,11> <описание>"+CRLF.
 *         RTC - "ГГГГ-ММ-ДД ЧЧ:ММ:СС" из rtc_time (Unix-время, секунды с 1970,
 *         без часового пояса); rtc_time == 0 - 19 пробелов (колонки ровные).
 *         Предназначена для console_fn, чтобы любой приёмник (COM, UART, TCP)
 *         выдавал единый читаемый текст без ручного форматирования. Работает
 *         и при LOGGER_NO_ITM. Результат всегда завершён '\0' (если size > 0)
 *         и обрезается по size; семантика возвращаемого значения - как у
 *         snprintf.
 *
 * @param  buf         буфер результата (может быть NULL при size == 0 -
 *                      тогда только подсчёт длины)
 * @param  size        размер buf в байтах
 * @param  code        код лога (аргументы - те же, что получает console_fn)
 * @param  source_id   идентификатор источника события
 * @param  priority    приоритет кода
 * @param  value       значение переменной
 * @param  systick     HAL_GetTick() на момент события
 * @param  rtc_time    показание RTC на момент события, либо 0
 * @param  description текстовое описание кода, либо NULL (выводится "???")
 * @return длина полной строки без '\0'; если >= size - строка обрезана
 */
size_t LOGGER_FormatConsoleLine(char *buf, size_t size, uint16_t code, uint16_t source_id,
                                 LOGGER_Priority_t priority, int32_t value, uint32_t systick,
                                 uint32_t rtc_time, const char *description);

/* ------------------------------------------------------------------------ */
/*  Приём лога - главная горячая функция                                    */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Логирует событие: выводит его в консоль/SWO и, если включена
 *         буферизация, добавляет в буфер. Крайне часто вызываемая функция -
 *         оптимизирована по скорости,
 *         никаких проверок конфигурации в рантайме.
 *
 *         Если code отсутствует в таблице кодов (пользовательской или
 *         служебной) - запись всё равно выводится в консоль/SWO (с
 *         описанием "???", приоритет трактуется как LOGGER_PRIORITY_HIGH
 *         только для целей вывода), но НЕ буферизуется (приоритет для неё
 *         достоверно не определён) - это сигнал разработчику о
 *         рассинхронизации кода лога с таблицей.
 *
 * @param  code       код лога (см. таблицу в logger_codes.h)
 * @param  source_id  идентификатор источника события (какой именно
 *                     экземпляр/канал/устройство вызвал лог) - используется,
 *                     когда один код может прийти от нескольких равноправных
 *                     источников; если не нужно - передавайте 0
 * @param  value      значение переменной, сопровождающее событие
 */
void LOGGER_Log(uint16_t code, uint16_t source_id, int32_t value);

/* ------------------------------------------------------------------------ */
/*  Временные метки ("хлебные крошки" в коде) и их частота                  */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Фиксирует факт прохождения контрольной точки в коде - лёгкий способ
 *         трассировки порядка выполнения без привязки к таблице кодов
 *         пользователя. Эквивалентно
 *         LOGGER_Log(LOGGER_INTERNAL_CODE_MARK, mark_id, (int32_t)mark_id) +
 *         обновление статистики вызовов для LOGGER_GetMarkFrequency().
 * @param  mark_id  идентификатор метки, выбирается пользователем на месте
 *                   вызова. Статистика вызовов ведётся, только если
 *                   mark_id < LOGGER_MARK_MAX_IDS (иначе лог всё равно
 *                   происходит, просто без статистики)
 */
void LOGGER_Mark(uint16_t mark_id);

/**
 * @brief  Вычисляет среднюю частоту вызова конкретной метки (вызовов в
 *         секунду) по накопленной статистике. Деление с плавающей точкой
 *         выполняется только здесь, по явному запросу - не в LOGGER_Mark(),
 *         чтобы не нагружать горячий путь.
 * @param  mark_id       идентификатор метки (см. LOGGER_Mark())
 * @param  out_frequency  куда записать результат (вызовов/сек)
 * @retval HAL_OK - частота посчитана; HAL_ERROR - mark_id >= LOGGER_MARK_MAX_IDS,
 *         out_frequency == NULL, либо метка вызывалась ещё < 2 раз (нет
 *         интервала для расчёта)
 */
HAL_StatusTypeDef LOGGER_GetMarkFrequency(uint16_t mark_id, float *out_frequency);

/* ------------------------------------------------------------------------ */
/*  Статистика частоты обычных кодов ("болтливые" коды логов)               */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Вычисляет среднюю частоту вызова (вызовов в секунду) конкретного
 *         кода лога из пользовательской таблицы (logger_codes.h) - тот же
 *         расчёт, что и LOGGER_GetMarkFrequency(), но для обычных кодов, а
 *         не для меток. Статистика (кол-во вызовов, первый/последний
 *         HAL_GetTick()) обновляется автоматически на каждый LOGGER_Log() с
 *         известным кодом - никакого дополнительного кода в проекте не
 *         требуется. Деление с плавающей точкой выполняется ТОЛЬКО здесь, по
 *         явному запросу - не в LOGGER_Log(), чтобы не нагружать горячий путь.
 * @param  code           код лога (см. таблицу в logger_codes.h)
 * @param  out_frequency  куда записать результат (вызовов/сек)
 * @retval HAL_OK - частота посчитана; HAL_ERROR - out_frequency == NULL, code
 *         отсутствует в пользовательской таблице, либо код вызывался ещё
 *         < 2 раз (нет интервала для расчёта)
 */
HAL_StatusTypeDef LOGGER_GetCodeFrequency(uint16_t code, float *out_frequency);

/* ------------------------------------------------------------------------ */
/*  Принудительный сброс буфера                                             */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Немедленно записывает накопленный буфер в память через write_fn
 *         (если буферизация включена и в буфере есть записи), не дожидаясь
 *         достижения порога. Полезно перед переходом в сон/перед обновлением
 *         прошивки, чтобы не потерять ещё не сброшенные логи.
 * @retval HAL_OK - буфер пуст либо успешно сброшен; HAL_ERROR - буферизация
 *         не включена (LOGGER_Init() не вызывался или write_fn == NULL)
 */
HAL_StatusTypeDef LOGGER_Flush(void);

/* ------------------------------------------------------------------------ */
/*  Аварийное сохранение (сброс перед потерей питания/перезагрузкой)        */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Немедленно сохраняет накопленный буфер в память через write_fn -
 *         предназначена для вызова из аварийного контекста, непосредственно
 *         перед программной перезагрузкой или при обнаружении ожидаемой
 *         потери питания (например, в обработчике PVD/сторожевого таймера
 *         перед сбросом), когда важнее всего успеть записать данные, а не
 *         аккуратность вывода. В отличие от LOGGER_Flush() НЕ логирует
 *         служебное событие LOGGER_INTERNAL_CODE_FLUSH о самом сбросе - это
 *         минимизирует число операций на аварийном пути (лишний вызов
 *         console_fn/SWO-вывода не выполняется).
 *
 *         Как и LOGGER_Flush(), не блокирует надолго сама по себе - реальное
 *         время выполнения определяется предоставленной write_fn.
 * @retval HAL_OK - буфер пуст либо успешно сохранён; HAL_ERROR - буферизация
 *         не включена (LOGGER_Init() не вызывался или write_fn == NULL)
 */
HAL_StatusTypeDef LOGGER_EmergencySave(void);

/* ------------------------------------------------------------------------ */
/*  Диагностика переполнения буфера                                         */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Сколько записей потеряно из-за переполнения буфера с момента
 *         старта (кольцо полно, а освободить место сбросом не удалось - см.
 *         "Честные ограничения" в README). При штатной нагрузке и
 *         достаточной LOGGER_BUFFER_CAPACITY должно быть 0. Безопасно из
 *         любого контекста.
 * @return число потерянных записей
 */
uint32_t LOGGER_GetDroppedCount(void);

/**
 * @brief  Пик заполнения буфера (записей) с последнего LOGGER_Init() - для
 *         подбора LOGGER_BUFFER_CAPACITY: если близок к ёмкости, буфер мал
 *         для скорости потока логов и длительности write_fn.
 * @return максимальное число одновременно лежавших в буфере записей
 */
uint16_t LOGGER_GetBufferHighWater(void);

/**
 * @brief  Сколько раз сработала ошибка самой библиотеки (служебный код
 *         LOGGER_INTERNAL_CODE_BUFFER_OVERFLOW/UNKNOWN_CODE/RING_CORRUPT/
 *         WAIT_TIMEOUT/MARK_ID_RANGE/NOT_INIT) с момента старта. В журнал
 *         такая ошибка пишется только на 1-м, 2-м, 4-м, 8-м... срабатывании
 *         (защита от лавины), точный счёт - здесь.
 * @param  code служебный код ошибки (0x0004, 0x0006-0x000A)
 * @return число срабатываний; 0 для кода, не являющегося ошибкой библиотеки.
 *         Безопасно из любого контекста.
 */
uint32_t LOGGER_GetErrorCount(uint16_t code);

